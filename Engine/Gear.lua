local SCHOOLS = { 2, 3, 4, 5, 6, 7 } -- holy, fire, nature, frost, shadow, arcane (GetSpellBonusDamage)
local function Call(fn, ...)
  if type(fn) ~= "function" then return nil end
  local ok, a, b, c = pcall(fn, ...)
  if not ok then return nil end
  return a, b, c
end
local function Level() return ns.Num(ns.Value(UnitLevel, "player")) or 1 end
-- the DPS of the weapon worn in an inventory slot (16 main hand, 18 ranged), 0 without
local function WornDPS(slot)
  local link = Call(GetInventoryItemLink, "player", slot)
  if type(link) ~= "string" then return 0 end
  local c = Read(link)
  return c and c.dps or 0
end
-- your damage in the spec's currency (cur 1 AP, 2 ranged AP, 3 spell power, 4 healing), see the head of the file
function ns.GearDamage(cur, level)
  if cur == nil and mine.dmg then return mine.dmg end
  local w = ns.GearWeights()
  cur = cur or (w and w.cur) or 0
  level = level or Level()
  local d = 0
  if cur == 1 then
    local base, pos, neg = Call(UnitAttackPower, "player")
    d = 14 * WornDPS(16) + (ns.Num(base) or 0) + (ns.Num(pos) or 0) + (ns.Num(neg) or 0)
  elseif cur == 2 then
    local base, pos, neg = Call(UnitRangedAttackPower, "player")
    d = 14 * WornDPS(18) + (ns.Num(base) or 0) + (ns.Num(pos) or 0) + (ns.Num(neg) or 0)
  elseif cur == 3 then
    local sp = 0
    for _, school in ipairs(SCHOOLS) do sp = math.max(sp, ns.Num(Call(rawget(_G, "GetSpellBonusDamage"), school)) or 0) end
    d = 8 * level + sp
  elseif cur == 4 then
    d = 10 * level + (ns.Num(Call(rawget(_G, "GetSpellBonusHealing"))) or 0)
  end
  d = math.max(d, 1)
  if cur == ((w and w.cur) or 0) and level == Level() then mine.dmg = d end
  return d
end
-- (26.11.2026) talents with spell hit for one school only: the game's spell hit (GetSpellHitModifier) leaves them out,
-- they are "spell modifiers" (aura 107, misc 16, SpellEffect of the client build 71037). Hit talents for all attacks or
-- all spells are plain hit auras (54, 55: Precision, Suppression, Tidal Focus, Surefooted, Nature's Reach, Nature's
-- Guidance, the dwarves' Artisan's Precision) and in the game's numbers already. The value is the talent's whole worth;
-- with fewer ranks learned it counts by rank (talent found by its icon), else in full while the spell is known.
local SCHOOL_HIT_TALENTS = {
  shadow = { { 15260, 5 } },           -- Shadow Focus (priest, Shadow)
  arcane = { { 11222, 2 } },           -- Arcane Focus (mage, Arcane)
  holy = { { 1309957, 18 }, { 1310904, 8 } }, -- Holy Precision (priest), Divine Precision (paladin)
}
local function TalentShare(spellID)
  local tex = Call(rawget(_G, "GetSpellTexture"), spellID)
  if not tex and C_Spell and C_Spell.GetSpellTexture then tex = Call(C_Spell.GetSpellTexture, spellID) end
  local info, tabs = rawget(_G, "GetTalentInfo"), ns.Num(Call(rawget(_G, "GetNumTalentTabs"))) or 0
  if tex and type(info) == "function" then
    for tab = 1, tabs do
      for i = 1, ns.Num(Call(rawget(_G, "GetNumTalents"), tab)) or 0 do
        local ok, _, icon, _, _, rank, maxRank = pcall(info, tab, i)
        if ok and icon == tex and ns.Num(maxRank) and maxRank > 0 then return (ns.Num(rank) or 0) / maxRank end
      end
    end
  end
  local known = Call(rawget(_G, "IsPlayerSpell"), spellID)
  return known and 1 or 0
end
-- the school a caster's weights favour (sd_<school> highest), nil for none
local function MainSchool(w)
  local best, bestV
  for _, school in ipairs({ "holy", "fire", "nature", "frost", "shadow", "arcane" }) do
    local v = w and w["sd_" .. school] or 0
    if v > 0 and (not bestV or v > bestV) then best, bestV = school, v end
  end
  return best
end
function ns.GearSchoolTalentHit(school)
  local h = 0
  for _, t in ipairs(SCHOOL_HIT_TALENTS[school or ""] or {}) do h = h + t[2] * TalentShare(t[1]) end
  return h
end

-- the hit you have now in percent, as Forever's character frame counts it (PaperDollFrame_SetHitChance: the rating's
-- bonus plus GetHitModifier, GetRangedHitModifier, GetSpellHitModifier): melee, spells, ranged
local function PlayerHit()
  if mine.hit then return mine.hit[1], mine.hit[2], mine.hit[3] end
  local melee = ns.Num(Call(rawget(_G, "GetHitModifier"))) or 0
  local spell = ns.Num(Call(rawget(_G, "GetSpellHitModifier"))) or 0
  local ranged = ns.Num(Call(rawget(_G, "GetRangedHitModifier"))) or melee
  local bonus = rawget(_G, "GetCombatRatingBonus")
  if type(bonus) == "function" then
    melee = melee + (ns.Num(Call(bonus, rawget(_G, "CR_HIT_MELEE") or 6)) or 0)
    ranged = ranged + (ns.Num(Call(bonus, rawget(_G, "CR_HIT_RANGED") or 7)) or 0)
    spell = spell + (ns.Num(Call(bonus, rawget(_G, "CR_HIT_SPELL") or 8)) or 0)
  end
  -- spell hit of the school talents for your spec's main school
  local w = ns.GearWeights()
  if w and (w.cur == 3) then spell = spell + ns.GearSchoolTalentHit(MainSchool(w)) end
  mine.hit = { melee, spell, ranged }
  return melee, spell, ranged
end
-- your hit of the kind the weights count (spells for casters and healers, ranged for hunters)
local function HitOfKind(w)
  local melee, spell, ranged = PlayerHit()
  if w.cur == 3 or w.cur == 4 then return spell end
  if w.cur == 2 then return ranged end
  return melee
end
ns.GearPlayerHit = PlayerHit
-- the caps for your level (see HIT_CAP): melee and spells, then how far hit above them still counts a little (soft)
-- (26.11.2026, Daniel: "wäre bei zaubern nicht mehr als 6% sinnvoll? wenn sie nachher 17 brauchen?", gewählt "Teilweise
-- bis 17 %") below level 50 hit counts in full up to 6 %, then a third (SOFT_SHARE) up to the level 50 caps (8 %, 17 %):
-- it does nothing against mobs now, but bosses from level 50 need it
local SOFT_SHARE = 1 / 3
function ns.GearHitCaps(level)
  if (level or Level()) < LOW_LEVEL then return LOW_HIT_CAP, LOW_SPELL_HIT_CAP, HIT_CAP, SPELL_HIT_CAP end
  return HIT_CAP, SPELL_HIT_CAP, HIT_CAP, SPELL_HIT_CAP
end
-- percent of hit that counts: in full up to cap, SOFT_SHARE between cap and soft, nothing above (have: your hit without it)
local function HitCounted(hit, have, cap, soft)
  if hit <= 0 then return 0 end
  local full = math.max(0, math.min(hit, cap - have))
  local from = math.max(have, cap)
  local part = math.max(0, math.min(have + hit, soft) - from)
  return full + part * SOFT_SHARE
end
ns.GearHitCounted = HitCounted
-- links you wear (to know whether an item's hit is part of PlayerHit already)
local function Worn()
  if mine.worn then return mine.worn end
  local t = {}
  for slot = 1, 19 do
    local link = Call(GetInventoryItemLink, "player", slot)
    if type(link) == "string" then t[link] = true end
  end
  mine.worn = t
  return t
end
-- the points of 1 % hit and 1 % crit for the weights w (spell or physical by the spec), and whether spells count
-- (26.11.) your own fixed numbers from the options win (hitFix ... from ns.GearSetOverrides)
local function HitCrit(w, dmgCur)
  if (w.cur or 0) == 0 then return w.hitFix or w.hit or 0, w.critFix or w.crit or 0, w.shitFix or w.shit or 0 end
  local per = w.cur == 1 and w.ap or w.cur == 2 and w.rap or w.cur == 3 and w.sd or w.heal or 0
  local d = (dmgCur or ns.GearDamage()) / 100 * per
  local hitP, critP = (w.hitk or 0) * d, (w.critk or 0) * d
  if w.cur == 3 or w.cur == 4 then
    return w.shitFix or hitP, w.scritFix or critP, 0
  end
  return w.hitFix or hitP, w.critFix or critP, 0
end

-- (26.11.2026) the weights of your spec in points as Geardon's options show them: the five primary stats (Agility with
-- its crit), hit and crit per 1 % (worth now, from your damage), dps per 1 weapon DPS, and the other keys. Without your
-- own numbers (the defaults of the spec), and with them. nil while the class is unknown.
local SHOWN = { "ap", "rap", "sd", "sd_holy", "sd_fire", "sd_nature", "sd_frost", "sd_shadow", "sd_arcane", "heal", "mp5",
  "hp5", "def", "dodge", "parry", "block", "bv", "wskill", "pen" }
function ns.GearShownWeights(own)
  local c, t = ClassID(), Tree()
  if not c then return nil end
  local spec = SPEC_WEIGHTS[c]
  local base = spec and (spec[t] or spec[0]) or WEIGHTS[c]
  local w = own and ns.GearWeights() or base
  if not w then return nil end
  local out = { str = w[1] or 0, agi = w[2] or 0, sta = w[3] or 0, int = w[4] or 0, spi = w[5] or 0 }
  local hitP, critP, fixedSpellHit = HitCrit(w)
  local spell = w.cur == 3 or w.cur == 4
  out.hit, out.crit = spell and 0 or hitP, spell and 0 or critP
  out.shit, out.scrit = spell and hitP or fixedSpellHit, spell and critP or 0
  if (w.agic or 0) > 0 and not spell then out.agi = out.agi + critP / w.agic end
  local hunter = c == HUNTER
  out.dps = w.dpsFix or 14 * ((hunter and w.rap) or w.ap or 0)
  for _, k in ipairs(SHOWN) do out[k] = w[k] or 0 end
  -- weapon skill: per point a share of 1 % hit
  if (w.wsk or 0) > 0 and not w.wskill then out.wskill = w.wsk * hitP end
  return out, c, t
end

-- Value of an item (link) for the player: total, then the parts stats (with AP and the secondary stats), armor, dps.
-- nil while unknown (the item is not loaded yet, or the class is unknown). hitBase: your hit without this item (default:
-- your hit now, less the item's own when you wear it).
function ns.GearValue(link, w, class, armorSta, hitBase)
  if type(link) ~= "string" then return nil end
  if not w then w, class = ns.GearWeights() end
  if not w then return nil end
  local c = Read(link)
  if not c then return nil end
  local eq = c.eq or NOEQ
  local stats = 0
  for i = 1, 5 do stats = stats + (w[i] or 0) * c[i] end
  local hunter = class == HUNTER
  local apW, rapW = w.ap, w.rap
  if apW == nil then -- the old class weights (tests, fallback)
    apW = (w[1] or 0) / (AP_PER_STR[class] or 1)
    rapW = hunter and (w[2] or 0) / 2 or 0
  end
  rapW = rapW or 0
  if hunter then
    -- "+X Attack Power" counts for ranged too; a ranged-only bonus only there
    stats = stats + math.max(c.rap, c.ap) * rapW + c.ap * apW
  else
    stats = stats + c.ap * apW + c.rap * rapW
  end
  -- secondary stats (26.11.2026)
  if next(eq) ~= nil or (w.agic or 0) > 0 then
    local hitP, critP, fixedSpellHit = HitCrit(w)
    local spellSpec = w.cur == 3 or w.cur == 4
    local cap, spellCap, softCap, softSpell = ns.GearHitCaps()
    local melee, spell = HitOfKind(w), HitOfKind(w)
    local mine_ = hitBase
    if spellSpec then
      local hit = eq.shit or 0
      local have = mine_ or (spell - (Worn()[link] and hit or 0))
      stats = stats + HitCounted(hit, have, spellCap, softSpell) * hitP + (eq.scrit or 0) * critP
    elseif w.cur == 0 then
      local hit = eq.hit or 0
      local have = mine_ or (melee - (Worn()[link] and hit or 0))
      stats = stats + HitCounted(hit, have, cap, softCap) * hitP + (eq.crit or 0) * critP
        + (eq.shit or 0) * fixedSpellHit
    else
      local hit = eq.hit or 0
      local have = mine_ or (melee - (Worn()[link] and hit or 0))
      local room = math.max(0, softCap - have)
      stats = stats + HitCounted(hit, have, cap, softCap) * hitP + (eq.crit or 0) * critP
      -- weapon skill: wsk of 1 % hit per point, while there is room under the cap
      if room > 0 then stats = stats + (eq.wskill or 0) * (w.wskill or (w.wsk or 0) * hitP) end
      -- Agility's crit (the weights carry only its attack power)
      if (w.agic or 0) > 0 then stats = stats + c[2] * critP / w.agic end
    end
    if next(eq) ~= nil then
      stats = stats + (eq.sd or 0) * (w.sd or 0) + (eq.heal or 0) * (w.heal or 0) + (eq.mp5 or 0) * (w.mp5 or 0)
        + (eq.hp5 or 0) * (w.hp5 or 0) + (eq.def or 0) * (w.def or 0) + (eq.dodge or 0) * (w.dodge or 0)
        + (eq.parry or 0) * (w.parry or 0) + (eq.block or 0) * (w.block or 0) + (eq.bv or 0) * (w.bv or 0)
        + (eq.pen or 0) * (w.pen or 0)
      for _, school in ipairs({ "holy", "fire", "nature", "frost", "shadow", "arcane" }) do
        local v = eq["sd_" .. school]
        if v then stats = stats + v * (w["sd_" .. school] or 0) end
      end
    end
  end
  local dps = 0
  if c.weapon and not c.wand then
    -- (26.11.) your own number per 1 DPS from the options (dpsFix) for the weapons that count
    if c.ranged then dps = (hunter and not c.thrown) and (w.dpsFix or 14 * rapW) * c.dps or 0
    elseif not hunter then dps = (w.dpsFix or 14 * apW) * c.dps
    else dps = 14 * apW * c.dps end
  end
  local armor = c.armor * (armorSta or ns.GearArmorStamina()) * (w[3] or 0)
  return stats + dps + armor, stats, armor, dps
end

-- hit of one side (a link or a list of links), in percent of the spec's kind
local function SideHit(x, w)
  if x == nil then return 0 end
  local key = (w.cur == 3 or w.cur == 4) and "shit" or "hit"
  local list = type(x) == "string" and { x } or x
  local h = 0
  for _, link in ipairs(list) do
    local c = Read(link)
    if c and c.eq then h = h + (c.eq[key] or 0) end
  end
  return h
end

-- Sum over a side: a link, a list of links (a two-hand weapon against both hands), or nil (an empty slot: 0).
-- Returns value, dps, ilvl, wand (the side is one wand), known.
local function Side(x, w, class, armorSta, hitBase)
  if x == nil then return 0, 0, 0, false, true end
  if type(x) == "string" then
    local v = ns.GearValue(x, w, class, armorSta, hitBase)
    if not v then return nil end
    local c = Read(x)
    return v, c.dps, c.ilvl, c.wand, true
  end
  local v, d, l, n = 0, 0, 0, 0
  for _, link in ipairs(x) do
    local a = ns.GearValue(link, w, class, armorSta, hitBase)
    if not a then return nil end
    local c = Read(link)
    v, d, l, n = v + a, d + c.dps, l + c.ilvl, n + 1
  end
  return v, d, n > 0 and l / n or 0, false, true
end

-- Is a better than b for the player? a, b: a link, a list of links (a two-hand weapon against both hands), or nil
-- (nothing worn there). b is what you wear: both sides count their hit against your hit without b.
-- Returns 1, -1 or 0 (alike in value, DPS and item level), then the value gain a - b; nil while either is unknown.
-- Wand against wand: the DPS decides when it differs by 5 % or more. Otherwise the value; when the values are alike,
-- the DPS, then the item level.
function ns.GearCompare(a, b)
  local w, class = ns.GearWeights()
  if not w then return nil end
  local armorSta = ns.GearArmorStamina()
  local hitBase
  if w.cur ~= nil then
    local have = HitOfKind(w)
    -- b worn: its hit is part of yours; b not worn (a question about two bag items): yours as it is
    local worn = Worn()
    local bWorn = b ~= nil and (type(b) ~= "string" or worn[b]) and (type(b) == "string" or worn[b[1] or ""])
    hitBase = have - (bWorn and SideHit(b, w) or 0)
  end
  local va, da, la, wa = Side(a, w, class, armorSta, hitBase)
  if not va then return nil end
  local vb, db, lb, wb = Side(b, w, class, armorSta, hitBase)
  if not vb then return nil end
  local gain = va - vb
  if wa and wb and math.max(da, db) > 0 and math.abs(da - db) >= WAND_DPS_SHARE * math.max(da, db) then
    return da > db and 1 or -1, gain
  end
  if math.abs(gain) >= 0.01 then return gain > 0 and 1 or -1, gain end
  if math.abs(da - db) >= 0.01 then return da > db and 1 or -1, gain end
  if la ~= lb then return la > lb and 1 or -1, gain end
  return 0, gain
end

-- (26.11.2026) lines for diagnostics (Geardon's /gd diag through DonDataAPI 5 GearDiag): spec, damage, your hit as the
-- game counts it next to the hit of your worn items, school talents, caps, and what 1 % hit and crit are worth now
function ns.GearDiagLines()
  local out = {}
  local w, class = ns.GearWeights()
  if not w then return { "gear: class unknown" } end
  local c, t = ClassID(), Tree()
  out[#out + 1] = ("gear: class %s tree %s, currency %s, damage %.0f, own numbers %s"):format(tostring(c), tostring(t),
    tostring(w.cur), ns.GearDamage(), overrides and "yes" or "no")
  local gameMelee = (ns.Num(Call(rawget(_G, "GetHitModifier"))) or 0)
  local gameSpell = (ns.Num(Call(rawget(_G, "GetSpellHitModifier"))) or 0)
  local gearMelee, gearSpell = 0, 0
  for link in pairs(Worn()) do
    local r = Read(link)
    if r and r.eq then gearMelee, gearSpell = gearMelee + (r.eq.hit or 0), gearSpell + (r.eq.shit or 0) end
  end
  local melee, spell, ranged = PlayerHit()
  local school = MainSchool(w)
  local cap, spellCap = ns.GearHitCaps()
  out[#out + 1] = ("hit: game melee %.1f (modifier %.1f), ranged %.1f, spell %.1f (modifier %.1f); worn items melee %.1f, spell %.1f; school talents %s %.1f; caps %d / %d")
    :format(melee, gameMelee, ranged, spell, gameSpell, gearMelee, gearSpell, tostring(school), school and w.cur == 3
      and ns.GearSchoolTalentHit(school) or 0, cap, spellCap)
  local hitP, critP = HitCrit(w)
  out[#out + 1] = ("worth now: 1 %% hit %.2f, 1 %% crit %.2f points"):format(hitP, critP)
  return out
end
