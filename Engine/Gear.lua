-- (26.11.2026) the weights of the class and talent tree (SPEC_WEIGHTS; tree 0, no talents yet: the levelling spec)
-- (26.11.2026, Daniel: "Die stateweight sollten auch in den optionen einstellbar sein ähnlich wie bei pawn") your own
-- weights for the spec you play, set by Geardon's options (DonDataAPI 5 SetGearOverrides): { class, tree, values }.
-- Values in points as the options show them: str agi sta int spi (agi: the whole worth of a point, its crit included),
-- hit crit shit scrit (per 1 %: fixed instead of the share of your damage), dps (per 1 weapon DPS), and the other keys
-- of SPEC_WEIGHTS. Only for the player's own class and tree; not kept here (Geardon keeps them).
local overrides
local PRIMARY_INDEX = { str = 1, agi = 2, sta = 3, int = 4, spi = 5 }
local FIX = { hit = "hitFix", crit = "critFix", shit = "shitFix", scrit = "scritFix", dps = "dpsFix" }
local function Merge(w, o)
  local c = {}
  for k, v in pairs(w) do c[k] = v end
  for k, v in pairs(o) do
    v = tonumber(v)
    if v then
      if PRIMARY_INDEX[k] then
        c[PRIMARY_INDEX[k]] = v
        if k == "agi" then c.agic = 0 end -- the whole worth: no crit added at runtime
      elseif FIX[k] then
        c[FIX[k]] = v
      else
        c[k] = v
      end
    end
  end
  return c
end
function ns.GearSetOverrides(class, tree, values)
  if type(values) == "table" and next(values) ~= nil then
    overrides = { class = tonumber(class), tree = tonumber(tree) or 0, values = values }
  else
    overrides = nil
  end
  Forget()
end

function ns.GearWeights(class, tree)
  if class == nil and tree == nil and mine.w then return mine.w, mine.class end
  local c = class or ClassID()
  if not c then return nil end
  local t = tree or Tree()
  local spec = SPEC_WEIGHTS[c]
  local w = spec and (spec[t] or spec[0]) or WEIGHTS[c]
  if class == nil and tree == nil and overrides and overrides.class == c and overrides.tree == t then
    w = Merge(w, overrides.values)
  end
  -- events reach the engine only after login: the tree is kept only once the game names one (or before level 10)
  if class == nil and tree == nil and (t ~= 0 or (ns.Num(ns.Value(UnitLevel, "player")) or 1) < 10) then
    mine.w, mine.class = w, c
  end
  return w, c
end
